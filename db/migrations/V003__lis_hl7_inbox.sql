CREATE SCHEMA IF NOT EXISTS lis;
CREATE TABLE IF NOT EXISTS lis.inbox_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_control_id VARCHAR(100) NOT NULL,
    source_system VARCHAR(80) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('Received','Processed','Failed')),
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    CONSTRAINT ux_lis_source_message UNIQUE (source_system, message_control_id)
);
CREATE INDEX IF NOT EXISTS ix_lis_inbox_status_received ON lis.inbox_messages(status,received_at DESC);
