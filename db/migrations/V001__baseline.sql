-- NOVA HBYS schema baseline. Run only against a fresh development/test database first.
CREATE SCHEMA IF NOT EXISTS patient;
CREATE SCHEMA IF NOT EXISTS clinical;
CREATE SCHEMA IF NOT EXISTS adt;
CREATE SCHEMA IF NOT EXISTS pharmacy;
CREATE SCHEMA IF NOT EXISTS billing;
CREATE SCHEMA IF NOT EXISTS publichealth;
CREATE SCHEMA IF NOT EXISTS integration;
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS patient.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mrn VARCHAR(32) NOT NULL UNIQUE,
    given_name VARCHAR(100) NOT NULL,
    family_name VARCHAR(100) NOT NULL,
    birth_date DATE NOT NULL CHECK (birth_date >= DATE '1900-01-01'),
    sex CHAR(1) NOT NULL CHECK (sex IN ('F','M','U')),
    phone VARCHAR(40),
    blood_type VARCHAR(3) CHECK (blood_type IS NULL OR blood_type IN ('A+','A-','B+','B-','AB+','AB-','0+','0-')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_patients_name ON patient.patients(family_name,given_name);

CREATE TABLE IF NOT EXISTS patient.encounters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patient.patients(id),
    encounter_type VARCHAR(20) NOT NULL CHECK (encounter_type IN ('Outpatient','Emergency','Inpatient')),
    status VARCHAR(20) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Admitted','Discharged','Closed','Cancelled')),
    chief_complaint VARCHAR(500),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ,
    external_ref VARCHAR(80) UNIQUE
);
CREATE INDEX IF NOT EXISTS ix_encounters_patient_opened ON patient.encounters(patient_id,opened_at DESC);
CREATE INDEX IF NOT EXISTS ix_encounters_status ON patient.encounters(status);

CREATE TABLE IF NOT EXISTS clinical.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL REFERENCES patient.encounters(id),
    order_type VARCHAR(20) NOT NULL CHECK (order_type IN ('LAB','RAD','DRUG','PROCEDURE','CONSULT')),
    code_system VARCHAR(30) NOT NULL,
    code VARCHAR(80) NOT NULL,
    description VARCHAR(250) NOT NULL,
    ordered_by VARCHAR(120) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Created' CHECK (status IN ('Created','Submitted','InProgress','Resulted','Verified','Cancelled','Rejected')),
    priority CHAR(1) NOT NULL DEFAULT 'R' CHECK (priority IN ('R','U','S')),
    clinical_note VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    external_ref VARCHAR(80) UNIQUE
);
CREATE INDEX IF NOT EXISTS ix_orders_encounter_created ON clinical.orders(encounter_id,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_orders_status_created ON clinical.orders(status,created_at);

CREATE TABLE IF NOT EXISTS clinical.lab_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES clinical.orders(id),
    analyte_code VARCHAR(80) NOT NULL,
    display VARCHAR(120) NOT NULL,
    value VARCHAR(120) NOT NULL,
    unit VARCHAR(30),
    reference_range VARCHAR(60),
    flag VARCHAR(2) NOT NULL CHECK (flag IN ('N','H','L','HH','LL')),
    critical BOOLEAN NOT NULL DEFAULT FALSE,
    resulted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_lab_results_order ON clinical.lab_results(order_id,resulted_at DESC);
CREATE INDEX IF NOT EXISTS ix_lab_results_critical ON clinical.lab_results(critical,resulted_at DESC) WHERE critical;

CREATE TABLE IF NOT EXISTS adt.beds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward VARCHAR(80) NOT NULL,
    room VARCHAR(20) NOT NULL,
    bed_no VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Occupied','Cleaning','OutOfService')),
    current_encounter_id BIGINT REFERENCES patient.encounters(id),
    UNIQUE(ward,room,bed_no),
    CHECK ((status='Occupied' AND current_encounter_id IS NOT NULL) OR status<>'Occupied')
);

CREATE TABLE IF NOT EXISTS adt.admissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL REFERENCES patient.encounters(id),
    bed_id BIGINT NOT NULL REFERENCES adt.beds(id),
    admitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    discharged_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'Admitted' CHECK (status IN ('Admitted','Discharged'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_active_admission_encounter ON adt.admissions(encounter_id) WHERE status='Admitted';
CREATE INDEX IF NOT EXISTS ix_admissions_status ON adt.admissions(status,admitted_at DESC);

CREATE TABLE IF NOT EXISTS pharmacy.drugs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    form VARCHAR(80) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock>=0),
    min_stock INTEGER NOT NULL DEFAULT 0 CHECK (min_stock>=0),
    unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price>=0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS pharmacy.prescriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL REFERENCES patient.encounters(id),
    prescribed_by VARCHAR(120) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Dispensed','Cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    dispensed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_prescriptions_status ON pharmacy.prescriptions(status,created_at DESC);
CREATE TABLE IF NOT EXISTS pharmacy.prescription_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL REFERENCES pharmacy.prescriptions(id),
    drug_id BIGINT NOT NULL REFERENCES pharmacy.drugs(id),
    dosage VARCHAR(80) NOT NULL,
    frequency VARCHAR(80) NOT NULL,
    duration_days INTEGER NOT NULL CHECK (duration_days>0),
    quantity INTEGER NOT NULL CHECK (quantity>0),
    dispensed_qty INTEGER NOT NULL DEFAULT 0 CHECK (dispensed_qty>=0)
);
CREATE TABLE IF NOT EXISTS pharmacy.stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drug_id BIGINT NOT NULL REFERENCES pharmacy.drugs(id),
    movement_type VARCHAR(30) NOT NULL,
    quantity INTEGER NOT NULL,
    reference VARCHAR(80),
    actor VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS billing.invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL REFERENCES patient.encounters(id),
    invoice_no VARCHAR(40) NOT NULL UNIQUE,
    payer VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Issued' CHECK (status IN ('Draft','Issued','Paid','Cancelled')),
    total NUMERIC(14,2) NOT NULL CHECK (total>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    paid_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_invoices_encounter ON billing.invoices(encounter_id,created_at DESC);
CREATE TABLE IF NOT EXISTS billing.invoice_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES billing.invoices(id),
    code VARCHAR(40) NOT NULL,
    description VARCHAR(200) NOT NULL,
    quantity NUMERIC(12,2) NOT NULL CHECK (quantity>0),
    unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price>=0),
    line_total NUMERIC(14,2) NOT NULL CHECK (line_total>=0)
);

CREATE TABLE IF NOT EXISTS publichealth.vaccinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patient.patients(id),
    vaccine_code VARCHAR(50) NOT NULL,
    vaccine_name VARCHAR(120) NOT NULL,
    dose_no INTEGER NOT NULL CHECK (dose_no>0),
    lot_no VARCHAR(60),
    administered_at TIMESTAMPTZ NOT NULL,
    administered_by VARCHAR(120) NOT NULL,
    external_event_id VARCHAR(80) UNIQUE
);
CREATE INDEX IF NOT EXISTS ix_vaccinations_patient ON publichealth.vaccinations(patient_id,administered_at DESC);

CREATE TABLE IF NOT EXISTS integration.outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target VARCHAR(120) NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    aggregate_type VARCHAR(60) NOT NULL,
    aggregate_id VARCHAR(80) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Processing','Sent','Failed','DeadLetter','Simulated')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error VARCHAR(1000),
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    idempotency_key VARCHAR(180) NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS ix_outbox_due ON integration.outbox(status,next_attempt_at,id);

CREATE TABLE IF NOT EXISTS audit.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL,
    username VARCHAR(120) NOT NULL,
    role VARCHAR(40) NOT NULL,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(100),
    details_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    previous_hash VARCHAR(64) NOT NULL,
    event_hash VARCHAR(64) NOT NULL UNIQUE,
    canonical_payload TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_audit_events_id_desc ON audit.events(id DESC);
CREATE OR REPLACE FUNCTION audit.reject_event_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit.events is append-only';
END;
$$;
DROP TRIGGER IF EXISTS audit_events_no_update ON audit.events;
CREATE TRIGGER audit_events_no_update BEFORE UPDATE OR DELETE ON audit.events
FOR EACH ROW EXECUTE FUNCTION audit.reject_event_mutation();

-- Also prevent a direct TRUNCATE from bypassing row-level append-only triggers.
DROP TRIGGER IF EXISTS audit_events_no_truncate ON audit.events;
CREATE TRIGGER audit_events_no_truncate BEFORE TRUNCATE ON audit.events
FOR EACH STATEMENT EXECUTE FUNCTION audit.reject_event_mutation();
