-- Prototype RIS reporting resource. This stores text reports only; no DICOM/PACS payloads.
CREATE TABLE IF NOT EXISTS clinical.radiology_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES clinical.orders(id),
    report_text VARCHAR(10000) NOT NULL CHECK (length(trim(report_text)) >= 10),
    impression VARCHAR(2000) NOT NULL CHECK (length(trim(impression)) >= 3),
    reported_by VARCHAR(120) NOT NULL,
    reported_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_radiology_reports_reported_at
    ON clinical.radiology_reports(reported_at DESC);
