CREATE TABLE IF NOT EXISTS adt.bed_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id BIGINT NOT NULL REFERENCES adt.admissions(id),
    from_bed_id BIGINT NOT NULL REFERENCES adt.beds(id),
    to_bed_id BIGINT NOT NULL REFERENCES adt.beds(id),
    transferred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    transferred_by VARCHAR(120) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    CHECK (from_bed_id <> to_bed_id)
);
CREATE INDEX IF NOT EXISTS ix_bed_transfers_admission_time
    ON adt.bed_transfers(admission_id, transferred_at DESC);
